export function translateKoreanTemplate(source) {
  let match;
  if ((match = source.match(/^(\d+)枠目$/))) return `${match[1]}번 슬롯`;
  if ((match = source.match(/^抽選 (\d+)$/))) return `${match[1]}회차 추첨`;
  if ((match = source.match(/^再付与 (\d+)$/))) return `${match[1]}회차 재부여`;
  if ((match = source.match(/^作成 (\d+)$/))) return `${match[1]}번째 제작`;
  if ((match = source.match(/^再付与(\d+)の(シリーズ|グループ)スキル$/))) return `${match[1]}회차 ${match[2] === "シリーズ" ? "시리즈" : "그룹"} 스킬`;
  if ((match = source.match(/^希望 (\d+)$/))) return `희망 ${match[1]}`;
  if ((match = source.match(/^(\d+)回先$/))) return `${match[1]}회 후`;
  if ((match = source.match(/^(\d+)本先$/))) return `${match[1]}개 제작 후`;
  if ((match = source.match(/^抽選(\d+)の(\d+)枠目$/))) return `${match[1]}회차 ${match[2]}번 슬롯`;
  if ((match = source.match(/^作成(\d+)の(\d+)枠目$/))) return `${match[1]}번째 제작 ${match[2]}번 슬롯`;
  if ((match = source.match(/^抽選(\d+)の(\d+)枠目を選択してください。$/))) return `${match[1]}회차의 ${match[2]}번 슬롯을 선택해 주세요.`;
  if ((match = source.match(/^作成(\d+)の(\d+)枠目を選択してください。$/))) return `${match[1]}번째 제작의 ${match[2]}번 슬롯을 선택해 주세요.`;
  if ((match = source.match(/^再付与(\d+)のシリーズとグループを選択してください。$/))) return `${match[1]}회차 시리즈·그룹 스킬을 선택해 주세요.`;
  if ((match = source.match(/^([\d,]+)候補$/))) return `후보 ${match[1]}개`;
  if ((match = source.match(/^候補 ([\d,]+)$/))) return `후보 ${match[1]}`;
  if ((match = source.match(/^([\d,]+)件$/))) return `${match[1]}개`;
  if ((match = source.match(/^([\d,]+)行・([\d,]+)列をCSVへ出力しました。$/))) return `CSV로 ${match[1]}행, ${match[2]}열을 내보냈습니다.`;
  if ((match = source.match(/^([\d.]+)秒$/))) return `${match[1]}초`;
  if ((match = source.match(/^作成カウンター ([\d,]+)から予測$/))) return `제작 카운터 ${match[1]}부터 예측`;
  if ((match = source.match(/^(\d+)回を表示$/))) return `${match[1]}회 표시`;
  if ((match = source.match(/^(\d+)回中 (\d+)回一致$/))) return `${match[1]}회 중 ${match[2]}회 일치`;
  if ((match = source.match(/^(シリーズ|グループ) ([\d,]+)$/))) return `${match[1] === "シリーズ" ? "시리즈" : "그룹"} ${match[2]}`;
  if ((match = source.match(/^現在のスキルカウンター ([\d,]+)$/))) return `현재 스킬 카운터: ${match[1]}`;
  if ((match = source.match(/^スキルカウンター ([\d,]+) を特定$/))) return `스킬 카운터 ${match[1]} 확인`;
  if ((match = source.match(/^(\d+)\/3 特定済み$/))) return `3개 중 ${match[1]}개 확인`;
  if (source === "3値を特定済み") return "3개 값 모두 확인";
  return null;
}
